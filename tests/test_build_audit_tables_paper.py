"""--paper-tables writes the three bodies that paper/main.tex \\input's, LF, and nothing else."""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "compare"))
import build_audit_tables as B  # noqa: E402


def test_paper_tables_names():
    assert B.PAPER_TABLES == {"tab_audit_1e4": "meanw_table.tex",
                              "tab_lowp_new": "lowp_table.tex",
                              "tab_depol": "depol_table.tex"}
    assert all(name in B.BUILDERS for name in B.PAPER_TABLES)
    assert set(B.PAPER_WRAP) == set(B.PAPER_TABLES)


def test_paper_tables_writes_three_lf_files(tmp_path):
    out = tmp_path / "out"
    paper = tmp_path / "paper"
    assert B.main(["--outdir", str(out), "--paper-tables", "--paper-dir", str(paper)]) == 0
    assert sorted(p.name for p in paper.iterdir()) == ["depol_table.tex", "lowp_table.tex",
                                                       "meanw_table.tex"]
    assert not out.exists()          # paper mode writes nothing to compare/out
    for p in paper.iterdir():
        raw = p.read_bytes()
        assert b"\r" not in raw
        assert raw.startswith(b"\\begin{tabular}")
        assert b"% generated by compare/build_audit_tables.py" in raw
        assert raw.endswith(b"\\bottomrule\n\\end{tabular}\n")
        assert b"\\\\\n" in raw     # at least one table row


def test_paper_tables_match_default_bodies(tmp_path):
    out = tmp_path / "out"
    paper = tmp_path / "paper"
    B.main(["--outdir", str(out)])
    B.main(["--outdir", str(tmp_path / "unused"), "--paper-tables", "--paper-dir", str(paper)])
    for name, fname in B.PAPER_TABLES.items():
        assert (paper / fname).read_text(encoding="utf-8") == \
            B.PAPER_WRAP[name] + (out / f"{name}.tex").read_text(encoding="utf-8") + B.PAPER_END


def test_fmt_pm_follows_the_pdg_rule():
    # The SE sets the precision: two digits when its leading three digits are
    # 100-354 (or round up to 1000), one digit for 355-949. No (0) any more, so
    # a 66-sigma deficit prints as such.
    assert B.fmt_pm(3.0082, 0.00006) == "3.00820(6)"
    assert B.fmt_pm(3.62, 0.16) == "3.62(16)"
    assert B.fmt_pm(0.027, 0.029) == "0.027(29)"
    assert B.fmt_pm(0.68, 0.098) == "0.68(10)"
    assert B.fmt_bias(-0.0036724, 0.0000558) == "-0.00367(6)"
    assert B.fmt_bias(0.000004, 0.000008) == "+0.000004(8)"
    assert B.fmt_bias(0.000001, 0.00006) == "0.00000(6)"


def test_truth_cell_caps_at_four_decimals():
    # The reference is often exact to many digits; past four decimals the SE is dropped.
    assert B.truth_cell(3.003951942, 1e-13) == "$3.0040$"
    assert B.truth_cell(4.0174, 0.0004) == "$4.0174(4)$"
    assert B.truth_cell(3.0550, 0.0012) == "$3.0550(12)$"
    assert B.truth_cell(4.592, 0.009) == "$4.592(9)$"
