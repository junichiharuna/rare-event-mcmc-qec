def build_audit(idx, args) -> str:
    out = [header(args)]
    for label, code, spread, bold in AUDIT_ROWS:
        obf = get(idx, "zh_rerun", code, "", 1e-2, "maxw", "OBF")
        zh = get(idx, "zh_rerun", code, "", 1e-2, "maxw", "Z+H")
        out.append("%s & %s & %s & %s & $%s$ \\\\"
                   % (label, truth_cell(obf["truth"], obf["truth_se"]),
                      cell(obf["bias"], obf["bias_se"], obf["converged"], bold=bold),
                      cell(zh["bias"], zh["bias_se"], zh["converged"]), spread))
    return "\n".join(out) + "\n"


RECT_BLOCKS = [
    (r"$\mathrm{AT}(5,5)$ ", "5x5", "0", ["uniform"],
     [(1e-2, r"10^{-2}"), (3e-3, r"3\times10^{-3}"), (1e-3, r"10^{-3}")]),
    (r"$\mathrm{AT}(3,11)$", "3x11", "8", ["short", "long"],
     [(1e-2, r"10^{-2}"), (3e-3, r"3\times10^{-3}"), (1e-3, r"10^{-3}")]),
    (r"$\mathrm{AT}(3,15)$", "3x15", "12", ["short", "long"],
     [(1e-2, r"10^{-2}"), (3e-3, r"3\times10^{-3}"), (1e-3, r"10^{-3}")]),
]
RECT_BOLD = {("3x11", 1e-3, "long", "OBF"), ("3x15", 1e-3, "long", "OBF")}


def build_rect(idx, args) -> str:
    out = [header(args)]
    for bi, (label, code, spread, inits, ps) in enumerate(RECT_BLOCKS):
        if bi:
            out.append(r"\midrule")
        for pi, (p, ptex) in enumerate(ps):
            head = ("%-19s & %-4s & " % (label, "$%s$" % spread) if pi == 0
                    else "%-19s & %-4s & " % ("", ""))
            e_obf = [get(idx, "rect", code, _rect_d(code), p, ini, "OBF")
                     for ini in inits]
            e_zh = get(idx, "rect", code, _rect_d(code), p, inits[-1], "Z+H")
            tcell = truth_cell(e_obf[0]["truth"], e_obf[0]["truth_se"])
            if len(inits) == 1:
                e = e_obf[0]
                mid = (r"\multicolumn{2}{c}{%s}"
                       % cell(e["bias"], e["bias_se"], e["converged"]))
            else:
                mid = " & ".join(
                    cell(e["bias"], e["bias_se"], e["converged"],
                         bold=(code, p, ini, "OBF") in RECT_BOLD)
                    for e, ini in zip(e_obf, inits))
            out.append("%s%-16s & %-11s & %s & %s \\\\"
                       % (head, "$%s$" % ptex, tcell, mid,
                          cell(e_zh["bias"], e_zh["bias_se"], e_zh["converged"])))
    return "\n".join(out) + "\n"


def _rect_d(code: str) -> str:
    # rect_audit_zh.csv carries d1/d2, not a single `d` column, so the condition
    # key's d slot is empty for every rectangular row.
    return ""


