def _lowp_body(idx, args, rows) -> str:
    out = []
    for i, (label, code, d, dataset, p, ptex, note) in enumerate(rows):
        if label and i:
            out.append(r"\midrule")
        obf = [_optional(idx, dataset, code, d, p, ini, "OBF")
               for ini in ("short", "long")]
        zh = [get(idx, dataset, code, d, p, ini, "Z+H") for ini in ("short", "long")]
        ptxt = "$%s$" % ptex + (note if note else "")
        out.append("%-22s & %-26s & %s & %s \\\\"
                   % (label, ptxt,
                      truth_cell(zh[0]["truth"], zh[0]["truth_se"]),
                      " & ".join(("--" if e is None else _biascell(e, args))
                                 for e in obf + zh)))
    return "\n".join(out) + "\n"


def _optional(idx, dataset, code, d, p, init, method):
    key = (dataset, code, str(d), p, init, method)
    return idx.get(key)


# P_L from cluster_results/subset_sampling.csv, filled by main().
PL_REF: Dict[tuple, float] = {}


def load_pl(results_dir: str) -> None:
    import csv as _csv
    path = os.path.join(results_dir, "subset_sampling.csv")
    if not os.path.exists(path):
        return
    alias = {"bb144": "bb144", "bb_l9m6": "bb_l9m6", "bb72": "bb72",
             "hgp_hamming3": "hgp_hamming3"}
    with open(path, newline="") as fh:
        for r in _csv.DictReader(fh):
            if r.get("noise") not in (None, "", "bit_flip"):
                continue
            code = alias.get(r["code_type"])
            if code:
                PL_REF[(code, float(r["p"]))] = float(r["p_L"])


