def _bold(e, args) -> bool:
    """The paper bolds the entries it wants read as a real bias."""
    se, b = e["bias_se"], abs(e["bias"])
    if not (se > 0):
        return False
    return b > BOLD_SIGMA * se and b >= args.bold_abs_min


def _biascell(e, args) -> str:
    return cell(e["bias"], e["bias_se"], e["converged"], bold=_bold(e, args))


def _audit3_ps(args, ps=None):
    """The p rows to print: an explicit list, else --p-only, else all three."""
    if ps is not None:
        return ps
    want = getattr(args, "p_only", None)
    if want is None:
        return AUDIT3_PS
    sel = [(p, t) for p, t in AUDIT3_PS if abs(p - want) <= 1e-12 * max(p, want)]
    if not sel:
        raise SystemExit("--p-only %g is not one of %s"
                         % (want, [p for p, _ in AUDIT3_PS]))
    return sel


def _audit3_body(idx, args, codes=None, ps=None, dataset=LOWP_DATASET) -> str:
    # With a single p there is nothing for a p column to vary over, so it is
    # dropped and the rate moves to the caption: one row per code, 7 columns.
    ps = _audit3_ps(args, ps)
    single_p = len(ps) == 1
    out = []
    first = True
    for _, rows in AUDIT3_GROUPS:
        rows = [r for r in rows if codes is None or r[1] in codes]
        if not rows:
            continue
        if not first:
            out.append(r"\midrule")
        first = False
        for row in rows:
            label, code, d, spread, inits, *rest = row
            ds = rest[0] if rest else dataset
            for pi, (p, ptex) in enumerate(ps):
                head = ("%-32s & %-4s & " % (label, "$%s$" % spread) if pi == 0
                        else "%-32s & %-4s & " % ("", ""))
                obf = [get(idx, ds, code, d, p, ini, "OBF") for ini in inits]
                zh = [get(idx, ds, code, d, p, ini, "Z+H") for ini in inits]
                tcell = truth_cell(obf[0]["truth"], obf[0]["truth_se"])
                if len(inits) == 1:
                    mid = (r"\multicolumn{2}{c}{%s} & \multicolumn{2}{c}{%s}"
                           % (_biascell(obf[0], args), _biascell(zh[0], args)))
                else:
                    mid = " & ".join(_biascell(e, args) for e in obf + zh)
                pcol = "" if single_p else "%-11s & " % ("$%s$" % ptex)
                out.append("%s%s%-12s & %s \\\\"
                           % (head, pcol, tcell, mid))
    return "\n".join(out) + "\n"


