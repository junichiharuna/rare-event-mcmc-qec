"""Emit LaTeX tabular bodies for the paper's audit tables, with convergence daggers.

Layouts and columns are byte-for-byte the ones already in paper/main.tex; only
three things change:
  * the truth column switches to the weight-stratified subset-sampling reference
    (cluster_results/subset_sampling.csv) wherever a row exists, else it keeps the
    direct-MC value the run CSV carries;
  * every bias is recomputed against that truth, with the combined SE;
  * entries that fail the convergence rule of compare/convergence_flags.py get a
    trailing $^\\dagger$.

Writes compare/out/tab_audit.tex, tab_rect.tex, tab_lowp.tex and tab_depol.tex.
Each file starts with a comment recording the exact thresholds
used, so a pasted table can be traced back to a rule.
With --paper-tables it instead writes the three whole tabulars that main.tex \\input's
(meanw_table.tex, lowp_table.tex and depol_table.tex) into paper/tables/.

Uncertainty formatting follows the PDG rule (analyze_dmc_speedup._val_unc): the SE keeps
two significant figures when its leading three digits are 100-354, one otherwise, and the
value shares its decimal place. Truth columns stop at 4 decimals and drop the SE when it
is finer than that (--truth-dec).
"""
from __future__ import annotations

import argparse
import math
import os
from typing import Dict, List, Optional, Sequence

from analyze_dmc_speedup import _unc_step, _val_unc
from convergence_flags import (DATASETS, OUTDIR, RESULTS, add_common_args,
                               entries_from_args)

DAGGER = r"^\dagger"
BOLD_SIGMA = 3.0


def fmt_pm(value: float, se: float, max_dec: Optional[int] = None) -> str:
    """`3.762(11)` style under the PDG rule, SE in units of the last digit. With
    `max_dec`, a value whose SE is finer than `max_dec` decimals is printed at
    `max_dec` decimals without an SE. No (0): a 66-sigma deficit reads as such."""
    if math.isnan(value):
        return "--"
    if math.isnan(se) or se <= 0:
        return "%.*f" % (3 if max_dec is None else max_dec, value)
    if max_dec is not None and -_unc_step(se) > max_dec:
        return "%.*f" % (max_dec, value)
    return _val_unc(value, se)


def fmt_bias(value: float, se: float) -> str:
    body = fmt_pm(abs(value), se)
    sign = "-" if value < 0 and float(body.split("(")[0]) != 0.0 else "+"
    if float(body.split("(")[0]) == 0.0:
        sign = ""
    return sign + body


def cell(value: float, se: float, converged: bool, *, bold: bool = False) -> str:
    txt = fmt_bias(value, se)
    if bold:
        txt = r"\mathbf{%s}" % txt
    return "$%s%s$" % (txt, "" if converged else DAGGER)


TRUTH_DEC = 4


def truth_cell(value: float, se: float, dec: Optional[int] = None) -> str:
    """Truth column, at most TRUTH_DEC decimals: the weight-stratified reference is
    often exact to many more digits, and then it prints without an SE (see --truth-dec)."""
    return "$%s$" % fmt_pm(value, se, TRUTH_DEC if dec is None else dec)


# ------------------------------------------------------------------ indexing --


def index(entries: Sequence[dict]) -> Dict[tuple, dict]:
    return {(e["dataset"], e["code"], str(e["d"]), e["p"], e["init"], e["method"]): e
            for e in entries}


def get(idx, dataset, code, d, p, init, method) -> dict:
    key = (dataset, code, str(d), p, init, method)
    if key not in idx:
        raise KeyError("missing entry %r" % (key,))
    return idx[key]


# How the primary rule's Rhat gets its within-chain SD, spelled out for the
# `% rule` comment the paper carries above each generated table.
WITHIN_DESC = {
    "chain": ("the pooled within-chain variance W (Gelman-Rubin), "
              "not the reference Var[w|F]"),
    "ref": "the MCMC-independent reference Var[w|F]",
}


def header(args, extra: str = "", primary: bool = False) -> str:
    if primary:
        rule = ("%% rule (primary, per-chain checkpoints): scaling sd(N) <= %g "
                "sd(N/%g) sqrt(1/%g); late-segment drift |z| <= %g; multi-start "
                "|short-long| <= %g SE; Rhat <= %g, with s_W from %s%s\n"
                % (args.scale_factor, 1.0 / args.scale_ref_frac,
                   1.0 / args.scale_ref_frac, args.drift_k, args.ms_k,
                   args.chain_rhat_max, WITHIN_DESC[args.rhat_within], extra))
    else:
        rule = ("%% rule (fallback): Rhat<=%s (%s), tau factor %g, drift '%s' "
                "|z|<=%g, aux cap<=%.0f%%, n/tau>=%g%s\n"
                % ("%.3f" % args.rhat_max if args.rhat_max
                   else "chi2 %g quantile" % (1 - args.rhat_alpha),
                   "fixed" if args.rhat_max else "K-aware",
                   args.tau_factor, args.drift_mode, args.drift_k,
                   100 * args.cap_frac, args.n_tau, extra))
    return ("% generated by compare/build_audit_tables.py -- do not edit by hand\n"
            + rule
            + "%% dagger = not converged; the number is a finite-chain value, "
              "not an ergodic-limit bias.\n"
              "%% bold = |bias| > %g combined SE and >= %g in absolute value.\n"
              % (BOLD_SIGMA, args.bold_abs_min))


