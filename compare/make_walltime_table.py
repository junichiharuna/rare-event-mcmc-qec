"""Absolute time-to-accuracy table for the paper (tab:ttawalltime).

Reads the numbers CSV written by compare/analyze_dmc_speedup.py
(cluster_results/dmc_speedup_table.csv) and writes
paper/tables/dmc_walltime_table.tex: the T_2% of direct Monte Carlo and of
Z+H in core-seconds, per code and physical error rate, i.e. the numerator and
denominator of tab:dmcspeedup.  A direct-MC cell is a budget floor (>=, mark a)
exactly where tab:dmcspeedup marks one (dmc_hard: the cutoff run saw no faulty
draw).  Z+H reached the target in every cell, so no Z+H cell is a floor.

Usage: python compare/make_walltime_table.py
"""
import csv
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(__file__))
from analyze_dmc_speedup import P_ORDER, ROW_LABEL, ROW_ORDER, _floor2, _fmt_p  # noqa: E402


def _fmt2(x, lb=False, mark=""):
    """Two significant figures at every magnitude (0.024, 0.83, 2.3, 12, 360),
    scientific notation from 10^3 up, as in analyze_dmc_speedup._fmt but without
    its one-decimal rounding of values below 10. A lower bound rounds down."""
    if not np.isfinite(x):
        return "--"
    if lb:
        x = _floor2(x)
    pre = r"\geq " if lb else ""
    post = rf"{{}}^{{\mathrm{{{mark}}}}}" if mark else ""
    if x >= 1000:
        e = int(np.floor(np.log10(x)))
        m = x / 10 ** e
        if round(m, 1) >= 10:
            m, e = m / 10, e + 1
        return rf"${pre}{m:.1f}\times10^{{{e}}}{post}$"
    if x >= 100:
        body = f"{round(x, -1):.0f}"
    elif x >= 10:
        body = f"{x:.0f}"
    elif x >= 1:
        body = f"{x:.1f}"
    else:
        e = int(np.floor(np.log10(x)))
        body = f"{x:.{1 - e}f}"
    return f"${pre}{body}{post}$"

IN = os.path.join(os.path.dirname(__file__), "..", "cluster_results", "dmc_speedup_table.csv")
TEX = os.path.join(os.path.dirname(__file__), "..", "paper", "tables", "dmc_walltime_table.tex")


def _b(s):
    return str(s).strip().lower() in ("true", "1")


def main():
    with open(IN, newline="") as f:
        rows = list(csv.DictReader(f))
    by = {}
    for r in rows:
        by[(r["code"], float(r["p"]))] = r
    n_runs = sorted({int(r["n_runs"]) for r in rows})
    if len(n_runs) != 1:
        raise ValueError(f"run count differs across cells: {n_runs}")
    n_runs = n_runs[0]
    if not all(_b(r["zh_reached"]) for r in rows):
        raise ValueError("a Z+H cell did not reach the target; add a floor mark before publishing")

    head = " & ".join(rf"\multicolumn{{2}}{{c}}{{{_fmt_p(p)}}}" for p in P_ORDER)
    sub = " & ".join(r"dMC & \zh{}" for _ in P_ORDER)
    cm = " ".join(rf"\cmidrule(lr){{{2 * i + 2}-{2 * i + 3}}}" for i in range(len(P_ORDER)))
    lines = [r"\begin{table}[t]", r"\centering", r"\footnotesize", r"\setlength{\tabcolsep}{5pt}",
             r"\begin{tabular}{l" + "cc" * len(P_ORDER) + "}",
             r"\toprule",
             "code & " + head + r" \\",
             cm,
             " & " + sub + r" \\",
             r"\midrule"]
    for code in ROW_ORDER:
        cells = []
        for p in P_ORDER:
            r = by.get((code, p))
            if r is None:
                cells += ["--", "--"]
                continue
            t_dmc, t_zh = float(r["t_dmc"]), float(r["t_zh"])
            hard = _b(r["dmc_hard"])
            cells.append(_fmt2(t_dmc, hard, "a" if hard else ""))
            cells.append(_fmt2(t_zh))
        lines.append(ROW_LABEL[code] + " & " + " & ".join(cells) + r" \\")
    cap = (r"Time to accuracy $T_{2\%}$ of \Cref{eq:tta} in core-seconds for direct Monte Carlo (dMC) "
           r"and for \zh{}, whose ratio is the speedup of \Cref{tab:dmcspeedup}. "
           rf"Entries are means over {n_runs} independent repeat runs (disjoint seeds), "
           r"rounded to two significant figures. "
           r"$\geq$ denotes a budget floor. "
           r"$(\mathrm{a})$ the direct-MC cutoff run saw no faulty draw, so its time is the budget "
           r"floor for the faulty draws the $2\%$ target requires, as in \Cref{tab:dmcspeedup}.")
    lines += [r"\bottomrule", r"\end{tabular}", r"\caption{" + cap + "}", r"\label{tab:ttawalltime}",
              r"\end{table}"]
    with open(TEX, "w", newline="\n") as f:
        f.write("% generated by compare/make_walltime_table.py -- do not edit by hand\n")
        f.write("\n".join(lines) + "\n")
    print(f"wrote {TEX}")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
