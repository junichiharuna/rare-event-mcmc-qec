"""Estimated cost of the logical error rate for the paper (tab:plcost).

Reads the numbers CSV written by compare/analyze_dmc_speedup.py
(cluster_results/dmc_speedup_table.csv) and writes
paper/tables/plcost_estimate_table.tex: the estimate of sec:plcost for a 2% logical
error rate at the target p, per code, in core-seconds.

  splitting  = N_LEVELS * (N_LEVELS - 1) * max_p T_2%(Z+H)
      N_LEVELS levels, each charged the largest measured Z+H time, times the
      N_LEVELS - 1 ratios whose errors add in quadrature (each ratio needs
      releps/sqrt(N_LEVELS - 1), i.e. N_LEVELS - 1 times the samples).
  direct MC  = T_2%(dMC at P_TARGET) * (1/releps^2) / N*
      1/releps^2 faulty draws for P_L in place of the N* >= 1 the mean weight needs
      (N* as in analyze_dmc_speedup.dmc_time_lower_bound).  A budget floor (dmc_hard)
      stays a floor.

These are estimates, not measurements: the full estimator was not run.

Usage: python compare/make_plcost_table.py
"""
import csv
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from analyze_dmc_speedup import P_ORDER, RELEPS, ROW_LABEL, ROW_ORDER, n_target  # noqa: E402
from make_walltime_table import _b, _fmt2  # noqa: E402

IN = os.path.join(os.path.dirname(__file__), "..", "cluster_results", "dmc_speedup_table.csv")
TEX = os.path.join(os.path.dirname(__file__), "..", "paper", "tables", "plcost_estimate_table.tex")

N_LEVELS = 21      # ladder of the example in sec:plcost: 10^-1 down to 10^-5
P_TARGET = 1e-5


def estimate(by, code):
    """(splitting bound, direct-MC cost, direct-MC is a floor) in core-seconds."""
    t_split = N_LEVELS * (N_LEVELS - 1) * max(float(by[(code, p)]["t_zh"]) for p in P_ORDER)
    r = by[(code, P_TARGET)]
    nstar = max(n_target(float(r["ew"]), float(r["vw"]), RELEPS), 1.0)
    t_dmc = float(r["t_dmc"]) * (1.0 / RELEPS ** 2) / nstar
    return t_split, t_dmc, _b(r["dmc_hard"])


def main():
    with open(IN, newline="") as f:
        by = {(r["code"], float(r["p"])): r for r in csv.DictReader(f)}
    lines = [r"\begin{table*}[t]", r"\centering", r"\footnotesize", r"\setlength{\tabcolsep}{6pt}",
             r"\begin{tabular}{lccc}",
             r"\toprule",
             r"code & splitting & direct MC & ratio \\",
             r"\midrule"]
    for code in ROW_ORDER:
        t_split, t_dmc, lb = estimate(by, code)
        if not t_split < t_dmc:
            raise ValueError(f"{code}: splitting bound {t_split:.3g} is not below direct MC {t_dmc:.3g}; "
                             "sec:plcost claims it is on every code")
        lines.append(" & ".join([ROW_LABEL[code], _fmt2(t_split), _fmt2(t_dmc, lb),
                                 _fmt2(t_dmc / t_split, lb)]) + r" \\")
    cap = (r"Estimated cost in core-seconds of the logical error rate to $2\%$ at $p=10^{-5}$ (\Cref{sec:plcost}). "
           rf"The splitting entry is the bound for a ladder of ${N_LEVELS}$ physical error rates, "
           rf"the largest \zh{{}} time of \Cref{{fig:ttawalltime}} multiplied by ${N_LEVELS}\times{N_LEVELS - 1}$. "
           rf"The direct-MC entry is its time for ${1.0 / RELEPS ** 2:.0f}$ faulty draws, "
           r"and the inequality sign $\geq$ marks a lower bound, where direct Monte Carlo collected no faulty draw within its budget. "
           r"The last column is the ratio of the two.")
    lines += [r"\bottomrule", r"\end{tabular}", r"\caption{" + cap + "}", r"\label{tab:plcost}",
              r"\end{table*}"]
    with open(TEX, "w", newline="\n") as f:
        f.write("% generated by compare/make_plcost_table.py -- do not edit by hand\n")
        f.write("\n".join(lines) + "\n")
    print(f"wrote {TEX}")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
